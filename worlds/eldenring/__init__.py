# category / is_dlc fields.
#   CURATION_DROP_BASE_GEAR  = base-game (non-DLC) WEAPON/ARMOR rated C/D/F.
#       Dropped from the pool so their locations stay randomized checks but the
#       junk no longer spreads. Runs whenever the option is on (DLC or not).
